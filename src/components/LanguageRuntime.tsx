function translateValue(value: string, language: 'id' | 'en') {
  if (language === 'id') return value.replace(/\bhousehold\b/gi, 'rumah');
  const exact = translations[value.trim()];
  if (exact) return exact;
  for (const [pattern, replacement] of dynamicTranslations) {
    const match = pattern.exec(value.trim());
    if (match) return replacement(match);
  }
  return value.replace(/\bhousehold\b/gi, 'home');
}

type TextState = { source: string; translated: string };
const textStates = new WeakMap<Text, TextState>();
const attributeStates = new WeakMap<Element, Map<string, TextState>>();
const translatableAttributes = ['aria-label', 'placeholder', 'title', 'alt'];
const businessContentSelector = '.data-row, .member-row, .schedule-history-item, .tomorrow-schedule-item, .notification-item, .dashboard-list-row, .cat-strip, .history-event, .schedule-restore-button, .assignee-row';
const translatableBusinessDescendantSelector = '.row-action, .primary, .secondary, .ghost-button, .danger-button, .status, .schedule-status, .schedule-custom-category, .occurrence-status, .role-badge, .status-badge';

function syncLanguage(root: Node, language: 'id' | 'en') {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const textNode = node as Text;
    const raw = textNode.nodeValue ?? '';
    const match = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match || !match[2]) continue;
    const parent = textNode.parentElement;
    const businessContent = parent?.closest(businessContentSelector);
    if (businessContent && !parent?.closest(translatableBusinessDescendantSelector)) continue;
    const current = match[2];
    let state = textStates.get(textNode);
    if (!state) state = { source: current, translated: current };
    else if (current !== state.source && current !== state.translated) state.source = current;
    const translated = translateValue(state.source, language);
    state.translated = translated;
    textStates.set(textNode, state);
    const next = `${match[1]}${translated}${match[3]}`;
    if (textNode.nodeValue !== next) textNode.nodeValue = next;
  }

  const elements = root instanceof Element ? [root, ...Array.from(root.querySelectorAll('*'))] : Array.from((root as Document).querySelectorAll('*'));
  for (const element of elements) {
    let states = attributeStates.get(element);
    for (const attribute of translatableAttributes) {
      const value = element.getAttribute(attribute);
      if (value === null) continue;
      states ??= new Map();
      let state = states.get(attribute);
      if (!state) state = { source: value, translated: value };
      else if (value !== state.source && value !== state.translated) state.source = value;
      const translated = translateValue(state.source, language);
      state.translated = translated;
      states.set(attribute, state);
      if (value !== translated) element.setAttribute(attribute, translated);
    }
    if (states) attributeStates.set(element, states);
  }
}

export function LanguageRuntime() {
  const { language } = useUIPreferences();

  useEffect(() => {
    document.documentElement.lang = language;
    const root = document.body;
    syncLanguage(root, language);
    let syncing = false;
    const observer = new MutationObserver(() => {
      if (syncing) return;
      syncing = true;
      syncLanguage(root, language);
      syncing = false;
    });
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatableAttributes });
    return () => observer.disconnect();
  }, [language]);

  return null;
}
